const BLOGS_STORAGE_KEY = "digibasera_stored_blog_posts";

export const loadStoredBlogPosts = (): BlogPost[] => {
  if (typeof window === "undefined") return BLOG_POSTS_DATA;
  try {
    const raw = localStorage.getItem(BLOGS_STORAGE_KEY);
    if (!raw) return BLOG_POSTS_DATA;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    return BLOG_POSTS_DATA;
  } catch (e) {
    console.error("Failed to load stored blog posts from localStorage", e);
    return BLOG_POSTS_DATA;
  }
};

export const saveBlogPosts = (posts: BlogPost[]): void => {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(BLOGS_STORAGE_KEY, JSON.stringify(posts));
    window.dispatchEvent(new Event("digibasera_blogs_updated"));
  } catch (e) {
    console.error("Failed to save blog posts to localStorage", e);
  }
};

export const resetBlogPostsToFactoryDefaults = (): BlogPost[] => {
  if (typeof window === "undefined") return BLOG_POSTS_DATA;
  try {
    localStorage.removeItem(BLOGS_STORAGE_KEY);
    window.dispatchEvent(new Event("digibasera_blogs_updated"));
  } catch (e) {
    console.error("Failed to reset blog posts", e);
  }
  return BLOG_POSTS_DATA;
};
